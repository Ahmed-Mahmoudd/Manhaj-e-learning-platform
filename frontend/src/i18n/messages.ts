export type MessageKey = keyof typeof messages.en;

export function t(
    locale: Locale,
    key: MessageKey,
    vars?: Record<string, string | number>,
): string {
    let text: string = messages[locale][key];
    if (vars) {
        for (const [k, v] of Object.entries(vars)) {
            text = text.replace(`{${k}}`, String(v));
        }
    }
    return text;
}
